/** Minimal valid PDF generator used for demo book files (no external dependency). */
export function makePdf(title: string, lines: string[]): Buffer {
  const esc = (s: string) => s.replace(/[\\()]/g, (m) => `\\${m}`);
  const asciiTitle = esc(title.replace(/[^\x20-\x7E]/g, '').trim() || 'Madrasti Shabwah');
  const body: string[] = [];
  body.push('BT /F1 20 Tf 60 780 Td (' + asciiTitle + ') Tj ET');
  body.push('BT /F1 11 Tf 60 755 Td (Madrasti Shabwah - Educational Platform) Tj ET');
  let y = 725;
  for (const line of lines.slice(0, 30)) {
    const safe = esc(line.replace(/[^\x20-\x7E]/g, '').trim());
    if (!safe) continue;
    body.push(`BT /F1 11 Tf 60 ${y} Td (${safe}) Tj ET`);
    y -= 18;
  }
  body.push('BT /F1 9 Tf 60 60 Td (Demo PDF generated by the platform. Replace with the official book file.) Tj ET');
  const content = body.join('\n');

  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',
    `<< /Length ${Buffer.byteLength(content, 'latin1')} >>\nstream\n${content}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ];

  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [];
  objects.forEach((obj, i) => {
    offsets.push(Buffer.byteLength(pdf, 'latin1'));
    pdf += `${i + 1} 0 obj\n${obj}\nendobj\n`;
  });
  const xrefOffset = Buffer.byteLength(pdf, 'latin1');
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets) {
    pdf += `${offset.toString().padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;
  return Buffer.from(pdf, 'latin1');
}
